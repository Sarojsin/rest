import psycopg2

c = psycopg2.connect("dbname=restaurant user=postgres password=tara host=localhost")
cur = c.cursor()

# Get full QR token for table T1
cur.execute("""
    SELECT tqt.token_hash, tqt.token_preview, tqt.status, tqt.created_at, rt.table_code, rt.display_name
    FROM table_qr_codes tqt
    JOIN restaurant_tables rt ON rt.id = tqt.table_id
    WHERE rt.table_code = 'T1' AND tqt.status = 'ACTIVE'
""")
rows = cur.fetchall()
print("Active QR codes for T1:")
for row in rows:
    print("  preview=%s | status=%s | created=%s" % (row[1], row[2], row[3]))
    print("  Full token_hash (not the raw token - this is hashed)")
    print("  NOTE: The raw token is not stored, only the hash")

# Check if there's a way to get the raw token
